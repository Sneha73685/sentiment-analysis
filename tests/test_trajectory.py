"""Trajectory unit-test coverage -- intentionally limited, and why.

src/mental_health_trajectory.py contains two small, pure, deterministic
helper functions that would otherwise be easy to unit test directly:

  - risk_to_score(risk): a fixed string->int mapping.
  - detect_trend(scores): counts increasing/decreasing steps in a score
    sequence and classifies the trend.

However, src/mental_health_trajectory.py has a module-level import,
`from src.mental_health_pipeline import analyze_text`, and
src/mental_health_pipeline.py loads two DistilBERT models at MODULE
IMPORT TIME (see tests/test_monte_carlo.py's module docstring for the
full explanation of that coupling -- it applies identically here, since
both files import from the same pipeline module).

This means `import src.mental_health_trajectory`, for any reason, always
loads both BERT models first. Per this phase's constraints (no BERT
loading in the unit suite unless unavoidable), that import is not
exercised here. Testing risk_to_score/detect_trend in isolation would
require either loading those models anyway or refactoring the module's
import structure -- both out of scope for this minimal test phase.

results/monte_carlo_results.csv and any trajectory-specific output are
not generated by this test suite.
"""

import pytest


def test_trajectory_helpers_not_unit_tested_due_to_model_loading_at_import():
    pytest.skip(
        "src.mental_health_trajectory transitively imports "
        "src.mental_health_pipeline, which loads BERT models at module "
        "import time. Skipped to avoid model loading in the unit suite -- "
        "see this file's module docstring."
    )
